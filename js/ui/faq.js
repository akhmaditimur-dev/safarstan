// Рендер FAQ
function renderFaq() {
    const container = document.getElementById('faqList');
    if (!container) return;

    container.innerHTML = FAQ_DATA.map((cat, catIdx) => `
        <div class="faq-category">
            <h3 class="faq-category__title">
                <i data-lucide="${cat.icon}"></i>
                ${cat.category}
            </h3>
            ${cat.items.map((item, itemIdx) => `
                <div class="faq-item" data-faq-item="1">
                    <button class="faq-item__question" data-faq-toggle="1">
                        <span>${item.q}</span>
                        <i data-lucide="chevron-down" class="faq-item__arrow"></i>
                    </button>
                    <div class="faq-item__answer" style="display:none;">
                        <p>${item.a}</p>
                    </div>
                </div>
            `).join('')}
        </div>
    `).join('');

    if (typeof lucide !== 'undefined') lucide.createIcons();
}

// === Обработчики ===
document.addEventListener('click', (e) => {
    // Открытие модалки FAQ — рендерим при каждом открытии
    const faqBtn = e.target.closest('#navFaqBtn');
    if (faqBtn) {
        renderFaq();
        return;
    }

    // Закрытие модалки
    if (e.target.closest('#faqClose')) {
        const modal = document.getElementById('faqModal');
        if (modal) modal.style.display = 'none';
        return;
    }
    if (e.target.id === 'faqModal') {
        e.target.style.display = 'none';
        return;
    }

    // Клик по вопросу — раскрыть/свернуть ответ
    const toggle = e.target.closest('[data-faq-toggle]');
    if (toggle) {
        const item = toggle.closest('.faq-item');
        const answer = item.querySelector('.faq-item__answer');
        const arrow = toggle.querySelector('.faq-item__arrow');
        if (!answer) return;

        const isHidden = answer.style.display === 'none';
        answer.style.display = isHidden ? 'block' : 'none';
        toggle.classList.toggle('active', isHidden);

        if (arrow) {
            arrow.setAttribute('data-lucide', isHidden ? 'chevron-up' : 'chevron-down');
            if (typeof lucide !== 'undefined') lucide.createIcons();
        }
        return;
    }
});